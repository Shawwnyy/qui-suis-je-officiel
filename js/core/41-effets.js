const effectsCanvas=
document.getElementById(
"effectsCanvas"
);
const effectsCtx=
effectsCanvas.getContext("2d");
let particles=[];
function resizeEffects(){
effectsCanvas.width=
window.innerWidth;
effectsCanvas.height=
window.innerHeight;
}
window.addEventListener(
"resize",
resizeEffects
);
resizeEffects();
function createConfetti(
count=100
){
const colors=[
"#a855f7",
"#ec4899",
"#22c55e",
"#3b82f6",
"#facc15",
"#f97316"
];
for(
let i=0;
i<count;
i++
){
particles.push({
x:
Math.random()*
innerWidth,
y:
-20-
Math.random()*
innerHeight,
vx:
(Math.random()-.5)*5,
vy:
2+
Math.random()*5,
size:
4+
Math.random()*7,
color:
colors[
Math.floor(
Math.random()*
colors.length
)
],
life:
100+
Math.random()*80,
rotation:
Math.random()*6,
vr:
(Math.random()-.5)*.2,
type:"confetti"
});
}
}
function createFirework(
x,
y,
color
){
for(
let i=0;
i<75;
i++
){
const angle=
Math.random()*
Math.PI*2;
const speed=
2+
Math.random()*7;
particles.push({
x:x,
y:y,
vx:
Math.cos(angle)*
speed,
vy:
Math.sin(angle)*
speed,
size:
2+
Math.random()*3,
color:color,
life:
55+
Math.random()*50,
gravity:.055,
type:"firework"
});
}
}
function fireworksShow(){
const colors=[
"#a855f7",
"#ec4899",
"#22c55e",
"#3b82f6",
"#facc15",
"#fff"
];
let count=0;
const interval=
setInterval(()=>{
createFirework(
100+
Math.random()*
(innerWidth-200),
100+
Math.random()*
(innerHeight*.45),
colors[
Math.floor(
Math.random()*
colors.length
)
]
);
count++;
if(count>=15){
clearInterval(
interval
);
}
},280);
createConfetti(180);
}
function animateEffects(){
effectsCtx.clearRect(
0,
0,
effectsCanvas.width,
effectsCanvas.height
);
particles=
particles.filter(
p=>p.life>0
);
particles.forEach(p=>{
p.x+=p.vx;
p.y+=p.vy;
if(p.type==="firework"){
p.vy+=p.gravity;
p.vx*=.985;
p.vy*=.985;
}else{
p.vy+=.05;
p.rotation+=p.vr;
}
p.life--;
effectsCtx.save();
effectsCtx.globalAlpha=
Math.max(
0,
Math.min(
1,
p.life/45
)
);
effectsCtx.fillStyle=
p.color;
if(p.type==="confetti"){
effectsCtx.translate(
p.x,
p.y
);
effectsCtx.rotate(
p.rotation
);
effectsCtx.fillRect(
-p.size/2,
-p.size/2,
p.size,
p.size*1.8
);
}else{
effectsCtx.beginPath();
effectsCtx.arc(
p.x,
p.y,
p.size,
0,
Math.PI*2
);
effectsCtx.fill();
}
effectsCtx.restore();
});
requestAnimationFrame(
animateEffects
);
}
animateEffects();
